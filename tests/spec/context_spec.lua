-- Context-sensitive dispatch (org.context): which feature handles C-c C-c,
-- C-c ', M-RET, M-/S-arrows, ... for what is under the cursor. The
-- contexts are detected for real; the feature commands they dispatch to
-- are replaced by recorders, so each case checks only the choice.

local context = require("org.context")

local restore = {}

--- Replace `mod.fn` by a recorder returning `ret` (true when nil); the
--- list of the argument lists it was called with.
local function stub(mod, fn, ret)
  local m = require(mod)
  local orig = m[fn]
  ok(type(orig) == "function", mod .. "." .. fn .. " is not a function")
  local calls = {}
  m[fn] = function(...)
    calls[#calls + 1] = { ... }
    if ret == nil then
      return true
    end
    return ret
  end
  restore[#restore + 1] = function()
    m[fn] = orig
  end
  return calls
end

local function restore_stubs()
  for i = #restore, 1, -1 do
    restore[i]()
  end
  restore = {}
end

--- Run `fn` from a Normal-mode mapping given `count` (v:count).
local function with_count(n, fn)
  local result
  _G.__org_context_spec = function()
    result = fn()
  end
  vim.keymap.set("n", "<F13>", "<Cmd>lua __org_context_spec()<CR>")
  vim.api.nvim_feedkeys(n .. vim.keycode("<F13>"), "x", false)
  vim.keymap.del("n", "<F13>")
  _G.__org_context_spec = nil
  return result
end

--- Run `fn` with the Visual selection `keys` active (from a mapping).
local function in_visual(keys, fn)
  local result
  _G.__org_context_spec = function()
    result = fn()
  end
  vim.keymap.set("x", "<F13>", "<Cmd>lua __org_context_spec()<CR>")
  vim.api.nvim_feedkeys(keys .. vim.keycode("<F13>"), "x", false)
  vim.keymap.del("x", "<F13>")
  _G.__org_context_spec = nil
  vim.cmd("normal! \27")
  return result
end

