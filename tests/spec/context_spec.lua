    lists.indent_item = function(delta, subtree)
      calls = calls + 1
      eq(-1, delta)
      eq(false, subtree)
      if calls <= 2 then
        vim.api.nvim_buf_set_lines(0, 1, 2, false, { "x" .. calls })
      end
      return true
    end
    restore[#restore + 1] = function()
      lists.indent_item = orig
    end
    with_count(5, context.promote)
    -- stopped after the first run that changed nothing
    eq(3, calls)
  end)

  it("a count stops on the first run that is not applicable", function()
    org_buffer({ "- a" }, { 1, 0 })
    local ind = stub("org.lists", "indent_item", false)
    eq(false, with_count(3, context.demote))
    eq(1, #ind)
  end)

  it("anything else is not applicable", function()
    org_buffer({ "text", "" }, { 1, 0 })
    eq(false, context.promote())
    eq(false, context.demote())
    vim.api.nvim_win_set_cursor(0, { 2, 0 })
    eq(false, context.promote())
  end)

  it("subtrees: items with their children, else the subtree of the entry", function()
    org_buffer({ "text", "* A", "body", "- item" }, { 4, 0 })
    local ind = stub("org.lists", "indent_item")
    local pro = stub("org.structure", "promote_subtree")
    local de = stub("org.structure", "demote_subtree")
    context.promote_subtree()
    context.demote_subtree()
    eq({ { -1, true }, { 1, true } }, ind)
    vim.api.nvim_win_set_cursor(0, { 3, 0 })
    context.promote_subtree()
    context.demote_subtree()
    eq(1, #pro)
    eq(1, #de)
    -- before the first headline: nothing
    vim.api.nvim_win_set_cursor(0, { 1, 0 })
    eq(false, context.promote_subtree())
    eq(false, context.demote_subtree())
  end)
end)

