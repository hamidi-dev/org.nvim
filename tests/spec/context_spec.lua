      eq(2, #exec)
    end)

    it("of a dynamic block: updates it", function()
      org_buffer({ "#+NAME: d", "#+BEGIN: clocktable", "#+END:" }, { 1, 0 })
      local lnum
      stub("org.dblock", "update_at_cursor")
      require("org.dblock").update_at_cursor = function()
        lnum = vim.api.nvim_win_get_cursor(0)[1]
        return true
      end
      context.context_action()
      eq(2, lnum)
      eq({ 1, 0 }, vim.api.nvim_win_get_cursor(0))
    end)

    it("of a plain list: repairs it; C-u adds checkboxes", function()
      local buf = org_buffer({ "#+NAME: l", "1) a", "1) b", "   - x" }, { 1, 0 })
      local refresh = stub("org.buffer", "refresh")
      context.context_action()
      eq({ "#+NAME: l", "1) a", "2) b", "   - x" }, buf_lines(buf))
      eq(0, #refresh)
      buf = org_buffer({ "#+ATTR_HTML: :class x", "- a", "- b", "  - x" }, { 1, 0 })
      -- C-u: v:count 4 (read-only, so vim.v is swapped)
      local real = vim.v
      vim.v = setmetatable({ count = 4 }, { __index = real })
      local res, err = pcall(context.context_action)
      vim.v = real
      ok(res, err)
      eq({ "#+ATTR_HTML: :class x", "- [ ] a", "- [ ] b", "  - x" }, buf_lines(buf))
