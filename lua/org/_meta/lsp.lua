---@meta
-- LuaLS type definitions for `require("org").setup({ extensions = { lsp = ... } })`.
-- Annotations only; never loaded at runtime. The `lsp` field of
-- org.Config.Extensions is declared in config.lua.

---@class org.Config.Extensions.Lsp
---`false` keeps the extension off.
---@field enabled? boolean
---Attach to every org buffer; with `false`, `:Org lsp_start` attaches the
---current one. (default: `true`)
---@field autostart? boolean
---Chooses the buffers to attach (default: file buffers with a name).
---@field filter? fun(bufnr: integer): boolean
---Called when the server attaches to a buffer.
---@field on_attach? fun(client: vim.lsp.Client, bufnr: integer)
---Capabilities, each `true` by default.
---@field features? org.Config.Extensions.Lsp.Features
---org-lint diagnostics.
---@field diagnostics? org.Config.Extensions.Lsp.Diagnostics
---Hover options.
---@field hover? { preview_lines?: integer, backlinks_all_headings?: boolean }
---List named src blocks and tables, and `<<targets>>`, in the document
---symbols. (default: `{ src_blocks = true, tables = true, targets = false }`)
---@field document_symbols? { src_blocks?: boolean, tables?: boolean, targets?: boolean }
---Symbol kinds by `vim.lsp.protocol.SymbolKind` name.
---(default: `{ heading = "Namespace", todo = "Event", done = "Constant",
---src_block = "Function", table = "Struct", target = "Key" }`)
---@field symbol_kinds? table<"heading"|"todo"|"done"|"src_block"|"table"|"target", string|integer>
---The files references, rename and workspace symbols look at.
---@field workspace? org.Config.Extensions.Lsp.Workspace
---Most workspace symbols returned. (default: `1000`)
---@field workspace_symbol_limit? integer
---Rewrite link descriptions equal to the old name, and write the files a
---rename had to load. (default: `{ update_descriptions = true, write_unloaded = true }`)
---@field rename? { update_descriptions?: boolean, write_unloaded?: boolean }
---Code actions: `entry` commands (`false` or a list of `{ action, title }`)
---and line `conversions`. (default: both on)
---@field code_actions? { entry?: boolean|{ [1]: string, [2]: string }[], conversions?: boolean }
---What formatting does: indent like `=`, align tables, realign tags.
---(default: `{ indent = true, tables = true, tags = true }`)
---@field formatting? { indent?: boolean, tables?: boolean, tags?: boolean }
---Inlay hints, each kind `true` by default.
---@field inlay_hints? org.Config.Extensions.Lsp.InlayHints
---Code lenses.
---@field code_lens? org.Config.Extensions.Lsp.CodeLens

---@class org.Config.Extensions.Lsp.InlayHints
---The time clocked in each subtree. (default: `true`)
---@field clock? boolean
---How far a DEADLINE or SCHEDULED date is ("in 3 d.", "2 d. ago"). (default: `true`)
---@field countdowns? boolean
---Time clocked against the Effort, rolled up from the children. (default: `true`)
---@field effort? boolean
---A `:block` range for the clock sums (default: `clock.display_default_range`).
---@field clock_range? string

---@class org.Config.Extensions.Lsp.CodeLens
---"Run block" on src blocks. (default: `true`)
---@field run_block? boolean
---"Update" on dynamic blocks. (default: `true`)
---@field dblock? boolean
---"Clock in" / "Clock out" on headlines: `"todo"` (not-done TODO headlines
---and the clocked one), `true` (every headline) or `false`. (default: `"todo"`)
---@field clock? boolean|"todo"

